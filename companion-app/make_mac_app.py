#!/usr/bin/env python3
"""Builds a double-clickable "Track Record.app" (macOS only).

    python make_mac_app.py                  # -> ~/Desktop/Track Record.app
    python make_mac_app.py --dest ~/Applications

Run it with the project's virtual environment active (see the README's
setup steps). The app it writes is a small launcher, not a bundled copy
of Python: it points at *this* checkout and *this* Python, so it's the
double-click equivalent of

    source .venv/bin/activate && cd companion-app && python track_record.py

That keeps it tiny and means there's nothing to rebuild when the code
changes - but it also means the app only works on the Mac, and from the
checkout, it was built from. If the project folder or its virtual
environment ever moves, run this again. A fully standalone app that
bundles Python and every dependency (Essentia + TensorFlow included) is
a much bigger job than this - see the README.

Anything the app prints, including a startup error, goes to
~/Library/Logs/TrackRecord.log, since there's no terminal window to show
it. Double-clicking while it's already running shows a notification
instead of starting a second copy.

The icon is drawn here (a record on a dark tile) with the Cocoa bindings
the app's own native window already depends on, then packed into an
.icns with macOS's iconutil - no image files to keep in the repo.
"""

from __future__ import annotations

import argparse
import plistlib
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUNDLE_ID = "com.track-record.launcher"
EXECUTABLE = "TrackRecord"

LAUNCHER = """#!/bin/bash
# Generated by make_mac_app.py - run it again if the project folder or
# its virtual environment moves.
COMPANION_APP={companion_app}
PYTHON={python}
LOG="$HOME/Library/Logs/TrackRecord.log"

# Only a real Python process running the script counts as "already
# running". A bare `pgrep -f track_record.py` matches ANY process whose
# command line merely mentions the filename - an editor with the file
# open, a grep, a shell - and the launcher then silently does nothing.
# The pattern is anchored to end with "<python> track_record.py", which
# is how the app's own process (and one started from Terminal) looks.
if pgrep -f "[Pp]ython[0-9.]* track_record\\.py$" >/dev/null; then
  osascript -e 'display notification "Track Record is already running." with title "Track Record"'
  exit 0
fi

cd "$COMPANION_APP" || exit 1
exec "$PYTHON" track_record.py >"$LOG" 2>&1
"""


def draw_iconset(out_dir: Path) -> None:
    """Renders every size macOS wants into `out_dir` as PNGs."""
    from AppKit import (
        NSBezierPath, NSBitmapImageRep, NSColor, NSDeviceRGBColorSpace,
        NSGradient, NSGraphicsContext, NSMakeRect, NSPNGFileType,
    )
    from Foundation import NSMakePoint

    def rgb(h: int, a: float = 1.0):
        return NSColor.colorWithSRGBRed_green_blue_alpha_(
            ((h >> 16) & 255) / 255, ((h >> 8) & 255) / 255, (h & 255) / 255, a)

    def circle(cx: float, cy: float, r: float):
        return NSBezierPath.bezierPathWithOvalInRect_(NSMakeRect(cx - r, cy - r, 2 * r, 2 * r))

    def render(s: int, path: Path) -> None:
        rep = NSBitmapImageRep.alloc().initWithBitmapDataPlanes_pixelsWide_pixelsHigh_bitsPerSample_samplesPerPixel_hasAlpha_isPlanar_colorSpaceName_bytesPerRow_bitsPerPixel_(
            None, s, s, 8, 4, True, False, NSDeviceRGBColorSpace, 0, 0)
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.setCurrentContext_(NSGraphicsContext.graphicsContextWithBitmapImageRep_(rep))

        # The standard macOS tile: ~10% transparent margin, rounded square.
        inset, size = s * 0.0977, s * 0.8046
        tile = NSBezierPath.bezierPathWithRoundedRect_xRadius_yRadius_(
            NSMakeRect(inset, inset, size, size), size * 0.2237, size * 0.2237)
        NSGradient.alloc().initWithStartingColor_endingColor_(
            rgb(0x3a3d46), rgb(0x16171b)).drawInBezierPath_angle_(tile, -90)

        cx = cy = s / 2
        r = size * 0.41
        rgb(0x0c0c0e).setFill()
        circle(cx, cy, r).fill()

        groove = 0.58  # fine concentric grooves
        while groove < 0.97:
            ring = circle(cx, cy, r * groove)
            ring.setLineWidth_(max(0.5, s / 700))
            rgb(0xffffff, 0.07).setStroke()
            ring.stroke()
            groove += 0.045

        for start in (28, 208):  # two soft sheen wedges
            wedge = NSBezierPath.bezierPath()
            wedge.moveToPoint_(NSMakePoint(cx, cy))
            wedge.appendBezierPathWithArcWithCenter_radius_startAngle_endAngle_(
                NSMakePoint(cx, cy), r * 0.97, start, start + 34)
            wedge.closePath()
            rgb(0xffffff, 0.07).setFill()
            wedge.fill()

        label = circle(cx, cy, r * 0.36)
        NSGradient.alloc().initWithStartingColor_endingColor_(
            rgb(0x5aa2f5), rgb(0x2a63c9)).drawInBezierPath_angle_(label, -90)
        rim = circle(cx, cy, r * 0.36)
        rim.setLineWidth_(max(1, s / 400))
        rgb(0xffffff, 0.25).setStroke()
        rim.stroke()
        rgb(0x0c0c0e).setFill()
        circle(cx, cy, r * 0.055).fill()  # spindle hole

        NSGraphicsContext.restoreGraphicsState()
        rep.representationUsingType_properties_(NSPNGFileType, None).writeToFile_atomically_(str(path), True)

    out_dir.mkdir(parents=True, exist_ok=True)
    for px, name in [
        (16, "icon_16x16"), (32, "icon_16x16@2x"), (32, "icon_32x32"), (64, "icon_32x32@2x"),
        (128, "icon_128x128"), (256, "icon_128x128@2x"), (256, "icon_256x256"),
        (512, "icon_256x256@2x"), (512, "icon_512x512"), (1024, "icon_512x512@2x"),
    ]:
        render(px, out_dir / f"{name}.png")


def build(dest_dir: Path, name: str) -> Path:
    app = dest_dir / f"{name}.app"

    # Never delete something this script didn't make.
    if app.exists():
        try:
            existing_id = plistlib.loads((app / "Contents" / "Info.plist").read_bytes()).get("CFBundleIdentifier")
        except Exception:
            existing_id = None
        if existing_id != BUNDLE_ID:
            sys.exit(f"{app} already exists and wasn't created by this script - not overwriting it. "
                     f"Pick another --dest or --name.")
        shutil.rmtree(app)

    macos, resources = app / "Contents" / "MacOS", app / "Contents" / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    with tempfile.TemporaryDirectory() as tmp:
        iconset = Path(tmp) / "TrackRecord.iconset"
        draw_iconset(iconset)
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(resources / "TrackRecord.icns")], check=True)

    (app / "Contents" / "Info.plist").write_bytes(plistlib.dumps({
        "CFBundleName": name,
        "CFBundleDisplayName": name,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": EXECUTABLE,
        "CFBundleIconFile": "TrackRecord",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": "1.0",
        "CFBundleVersion": "1",
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
    }))

    launcher = macos / EXECUTABLE
    launcher.write_text(LAUNCHER.format(
        companion_app=shlex.quote(str(HERE)),
        # sys.executable as invoked, not .resolve()d - resolving a venv's
        # python follows its symlink out to the system interpreter, which
        # has none of the project's packages installed.
        python=shlex.quote(sys.executable),
    ))
    launcher.chmod(0o755)
    app.touch()  # nudges Finder to pick up the new icon
    return app


def main() -> None:
    p = argparse.ArgumentParser(description="Build a double-clickable Track Record.app (macOS).")
    p.add_argument("--dest", default="~/Desktop", help="folder to put the app in (default: ~/Desktop)")
    p.add_argument("--name", default="Track Record", help="app name (default: Track Record)")
    args = p.parse_args()

    if sys.platform != "darwin":
        sys.exit("This only builds a macOS .app - run it on a Mac.")
    if not (HERE / "track_record.py").exists():
        sys.exit(f"Can't find track_record.py next to this script ({HERE}).")
    try:
        import nicegui  # noqa: F401
    except ImportError:
        sys.exit("The project's dependencies aren't installed in this Python - activate the virtual "
                 "environment first (source ../.venv/bin/activate), then run this again. The app "
                 "launches with whichever Python builds it.")

    dest = Path(args.dest).expanduser()
    dest.mkdir(parents=True, exist_ok=True)
    app = build(dest, args.name)
    print(f"Built {app}")
    print(f"  launches: {sys.executable} {HERE / 'track_record.py'}")
    print("  log:      ~/Library/Logs/TrackRecord.log")


if __name__ == "__main__":
    main()
